def logit(msg: str, level: str = "info"):
    """Compatibility wrapper: the logger itself lives in log.py."""
    log(msg, level)


def record(obj: dict):
    """Append one structured record to logs/requests.jsonl."""
    try:
        os.makedirs(LOGDIR, exist_ok=True)
        obj = dict(obj, ts=time.strftime("%Y-%m-%dT%H:%M:%S"))
        with LOGK, open(os.path.join(LOGDIR, "requests.jsonl"), "a", encoding="utf-8") as f:
            f.write(json.dumps(obj, ensure_ascii=False) + "\n")
    except Exception:
        pass


# A. counter normalization (CC_KEEP_CNT=1 disables it).
# Client-side CLAUDE_CODE_TOTAL_TOKENS_REMINDER=infinite (see _cc_local.json)
# makes the block byte-stable; this is the fallback, and it also covers the
# copies embedded in the environment block.
CNT = None if os.environ.get("CC_KEEP_CNT") else \
    re.compile(r"<total_tokens>\s*\d+\s*tokens left</total_tokens>")
CNT_FIX = "<total_tokens>" + os.environ.get("CC_CNT_N", "15000000") + " tokens left</total_tokens>"

# B/C. assistant header + empty blocks (CC_KEEP_AH=1 disables both).
AH = not os.environ.get("CC_KEEP_AH")
AH_HEAD = "<think>\n\n</think>\n\n"

# CC_CAP=1 adds the raw generated text to each request's record.
# The engine's reuse compares tokens, so recording the generated bytes is the
# only way to check them against what msgs_of re-renders.
CAP = os.environ.get("CC_CAP") == "1"

# D. thinking mode (CC_THINK=1, or a request carrying an Anthropic `thinking`).
# The model reasons inside <think>...</think>.  By default it is stripped: a
# client that did not ask has nowhere to put it, and AH_HEAD is what keeps the
# re-rendered history byte-identical to what was generated.  With thinking on it
# is sent as a thinking block ahead of the text AND re-rendered into history as
# the same <think>...</think>; skip that second half and every request after a
# thinking turn comes back cold.
#
# CC_THINK=0 is a hard lock, not a default: reasoning can be turned on by the
# live switch (GET /think?on=1), by the client's `thinking` field, and by
# history that already carries thinking blocks.  It is read once at startup as
# THINK_LOCKED; /think?on=1 is then refused, and msgs_of renders history with
# its reasoning stripped.  A lock a runtime call can undo is not a lock.
THINK = os.environ.get("CC_THINK", "1") == "1"     # startup default
# The hard lock: True means this process may never think.
THINK_LOCKED = not THINK
# The live switch.  A list because it is rebound from an HTTP handler while
# request threads read it; flipping it changes the prompt and costs one prefill.
_THINK = [THINK]


def want_think(req=None) -> bool:
    """Whether this reply's reasoning goes to the client (THINK_LOCKED wins)."""
    if THINK_LOCKED:
        return False
    return _THINK[0] or bool(req and req.get("thinking"))
# The same header, left open: AH_HEAD closes the block, this one asks it to start.
THINK_HEAD = "<think>\n"
# Thinking blocks carry a signature, sent as a signature_delta just before the
# block closes.  It must not be omitted: clients validate the shape and drop a
# block that arrives without one.
THINK_SIG = "ccsrv-local-signature"

