def sys_txt(system) -> str:
    """CC's system field is an array of content blocks (with cache_control); pull the text out."""
    if isinstance(system, str):
        return system
    if isinstance(system, list):
        return "\n".join(b if isinstance(b, str) else b.get("text", "")
                         for b in system if isinstance(b, (str, dict)))
    return ""


def msgs_of(system, msgs: list, tools: list | None) -> list:
    """Anthropic system/messages/tools -> [(role, content)] for the template to flatten."""
    out = []
    s = sys_txt(system)
    if tools:
        sch = json.dumps([{"name": t.get("name"), "description": t.get("description", ""),
                           "parameters": t.get("input_schema", {})} for t in tools],
                         ensure_ascii=False, indent=1)
        s = (s + "\n\n" + TOOLS_HINT.format(tools=sch)).strip()
    if s:
        out.append(("system", s))
    for m in msgs:
        role = m.get("role", "user")
        c = m.get("content")
        ch = []
        think = None
        if isinstance(c, str):
            ch.append(c)
        else:
            for b in (c or []):
                bt = b.get("type")
                if bt == "text":
                    ch.append(b.get("text", ""))
                elif bt == "thinking":
                    # This server's own reasoning from the previous turn.  It goes
                    # back as the <think> block it was generated from, so the bytes
                    # the model sees now equal the bytes it produced then.  Under
                    # THINK_LOCKED the body is dropped: re-sending a transcript's
                    # reasoning is itself an instruction to keep reasoning.
                    if not THINK_LOCKED:
                        think = strip_think_tags(b.get("thinking", ""))
                elif bt == "tool_use":
                    ch.append("<tool_call>\n" + json.dumps(
                        {"name": b.get("name"), "arguments": b.get("input", {})},
                        ensure_ascii=False) + "\n</tool_call>")
                elif bt == "tool_result":
                    inner = b.get("content")
                    if isinstance(inner, list):
                        inner = "".join(x.get("text", "") for x in inner
                                        if isinstance(x, dict))
                    ch.append("<tool_result>\n" + str(inner) + "\n</tool_result>")
        if role == "assistant" and AH:
            # C. Concatenate, never join: the blocks are a PARTITION of the bytes
            #    the model produced and the separators are already in the text.
            #    "\n".join added one newline the model never emitted, on every
            #    turn carrying both text and a tool call, and the KV holding the
            #    generated bytes can no longer serve that prefix.
            body = "".join(ch)
            if think is not None:
                # Rebuild the generated bytes exactly: "<think>\n" + reasoning +
                # "</think>\n\n" + answer, so nothing may be added around it.
                out.append((role, f"<think>\n{think}</think>\n\n" + body))
            else:
                out.append((role, AH_HEAD + body))
        else:
            out.append((role, "\n".join(ch)))
    return out


def strip_think_tags(t: str) -> str:
    """Remove a <think>/</think> wrapper a client put back around reasoning.

    The engine sends reasoning without the tags (the prompt already opened the
    block), but the client echoes them back, so stripping them keeps the render
    idempotent.
    """
    if t.startswith("<think>"):
        t = t[7:]
        if t.startswith("\n"):
            t = t[1:]          # the newline the block puts after the tag
    if t.endswith("</think>"):
        t = t[:-8]
    return t


def drop_think(t: str) -> str:
    """Strip <think>...</think> (an unclosed one too)."""
    while "<think>" in t:
        i = t.find("<think>")
        j = t.find("</think>", i)
        t = t[:i] + (t[j + 8:] if j >= 0 else "")
    return t.strip()


def split_think(t: str, opened: bool = False):
    """-> (thinking, rest).  ``opened`` means the prompt already carried the
    opening tag, so only the closing one appears in the output."""
    if opened:
        body = t[7:] if t.startswith("<think>") else t   # tolerate a doubled tag
        j = body.find("</think>")
        if j < 0:
            return body, ""           # never closed: all of it is reasoning
        return body[:j], drop_think(body[j + len("</think>"):])
    i = t.find("<think>")
    if i < 0:
        return "", t
    lead = t[:i]                      # text before the block is the reply's, not its reasoning
    body = t[i + len("<think>"):]
    j = body.find("</think>")
    if j < 0:
        return body, drop_think(lead)
    # The tail goes through drop_think, not just a slice: a reply can carry more
    # than one block and drop_think strips every one of them, which slicing
    # here would leave in the text.
    return body[:j], drop_think(lead + body[j + len("</think>"):])


def calls_of(text: str):
    """Pull <tool_call>...</tool_call> out of generated text.  Lenient: if JSON
    parsing fails, fall back to brace matching."""
    pre, calls, rest = [], [], text
    while True:
        i = rest.find("<tool_call>")
        if i < 0:
            break
        j = rest.find("</tool_call>", i)
        body = rest[i + 11: j if j >= 0 else len(rest)]
        pre.append(rest[:i])
        rest = rest[j + 12:] if j >= 0 else ""
        o = None
        try:
            o = json.loads(body.strip())
        except Exception:
            k = body.find("{")
            if k >= 0:
                d = 0
                for e in range(k, len(body)):
                    d += (body[e] == "{") - (body[e] == "}")
                    if d == 0:
                        try:
                            o = json.loads(body[k:e + 1])
                        except Exception:
                            pass
                        break
        if isinstance(o, dict) and o.get("name"):
            calls.append({"name": o["name"], "arguments": o.get("arguments") or {}})
    pre.append(rest)
    return "".join(pre), calls


def sse(h, ev: str, data: dict):
    """Write one SSE frame.  False once the client is gone."""
    if getattr(h, "_gone", False):
        return False
    try:
        h.wfile.write(f"event: {ev}\ndata: {json.dumps(data, ensure_ascii=False)}\n\n".encode())
        h.wfile.flush()
        return True
    except (ConnectionError, OSError):
        # Latch the disconnect; an unguarded write turns one hang-up into a
        # traceback per token.  close_connection keeps keep-alive off the socket.
        h._gone = True
        h.close_connection = True
        return False


def usage(i: int, o: int, cache_read: int = 0) -> dict:
    """Anthropic usage.  Claude Code records these fields into its session
    transcript and computes its hit rate from them, so they must be real.
    cache_creation_input_tokens stays 0: every forwarded token also lands in the
    KV, so the forwarded count is reported as plain input rather than twice.
    """
    return {"input_tokens": max(0, i - cache_read), "output_tokens": o,
            "cache_creation_input_tokens": 0, "cache_read_input_tokens": cache_read}


def prepare(req):
    """Anthropic request -> (prompt token ids, turn key)."""
    m = msgs_of(req.get("system", ""), req.get("messages", []), req.get("tools") or [])
    turn = turn_key(m)
    # Use the template only when it actually RENDERED.  CC puts a role: system
    # message at index 1, 4, 7 and the template refuses any system message that
    # is not first, so the fallback is the path a real client actually takes;
    # branching on E.ct.active alone silently changes the prompt there.
    p = E.tmpl_jinja(m, True, want_think(req)) if E.ct.active else None
    if p is None:
        if not AH:
            p = E.tmpl_lib(m, add_ass=True)
        else:
            # B. the assistant header must come from the template, not be
            #    hardcoded: the layout (newlines, separator before the body)
            #    belongs to the template.  Render one sentinel message and take
            #    the span between the base rendering and the sentinel.  Do not
            #    use endswith(SENT) -- the template completes the assistant
            #    message -- and find() must start at len(base), which is what
            #    brings in the separator and makes the two sides identical.
            SENT = "SENTINELPROBE"
            base = E.tmpl_lib(m, add_ass=False)
            probe = E.tmpl_lib(m + [("assistant", SENT)], add_ass=False)
            i = probe.find(SENT, len(base))
            # D. Thinking is a template variable (enable_thinking) and
            #    llama_chat_apply_template takes no template kwargs, so this span
            #    is chosen here: leaving the block OPEN keeps the round trip
            #    closed -- the model produces "<think>\n" + reasoning +
            #    "</think>\n\n" + answer and msgs_of rebuilds those bytes.
            head = THINK_HEAD if want_think(req) else AH_HEAD
            p = base + (probe[len(base):i] if i >= 0 else "") + head
    if CNT is not None:
        # A. pin the counter to a constant so the prefix is stable.
        p = CNT.sub(CNT_FIX, p)
    return E.tok(p), turn


def render(req) -> list[int]:
    """Compatibility shim: prompt ids only."""
    return prepare(req)[0]


class Api(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *a):
        pass

    def _head(self, code, ctype, extra=()):
        """Send a status line and headers.  False once the client is gone."""
        if getattr(self, "_gone", False):
            return False
        try:
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            for k, v in extra:
                self.send_header(k, v)
            self.end_headers()
            self._hdr_sent = True
            return True
        except (ConnectionError, OSError):
            self._gone = True
            self.close_connection = True
            return False

    def _write(self, b):
        """Write a response body, latched the same way as _head()."""
        if getattr(self, "_gone", False):
            return False
        try:
            self.wfile.write(b)
            # Flush here, not at the end of handle_one_request: a body that
            # fits the buffer would otherwise touch the socket outside this guard.
            self.wfile.flush()
            return True
        except (ConnectionError, OSError):
            self._gone = True
            self.close_connection = True
            return False

    def _send(self, code, obj):
        b = json.dumps(obj, ensure_ascii=False).encode()
        if not self._head(code, "application/json",
                          [("Content-Length", str(len(b)))]):
            return False
        return self._write(b)

    def do_GET(self):
        if self.path.startswith("/health"):
            return self._send(200, {"ok": True})
        if self.path.startswith("/stats"):
            return self._send(200, {"eng": E.line() if E else None})
        if self.path.startswith("/think"):
            # GET /think -> current state, GET /think?on=1|0 -> set it
            if "on=" in self.path:
                v = self.path.split("on=", 1)[1].split("&")[0].strip().lower()
                want = v not in ("0", "false", "off", "no")
                if THINK_LOCKED and want:
                    # Refused loudly: a switch that reports success and
                    # changes nothing is worse than one that says no.
                    logit("thinking refused: CC_THINK=0 locks it off for this "
                          "process (restart with CC_THINK=1 to enable)",
                          "warn")
                    return self._send(200, {"think": False, "locked": True,
                                            "error": "CC_THINK=0 is a hard lock; "
                                                     "restart with CC_THINK=1"})
                _THINK[0] = want
                logit(f"thinking {'on' if _THINK[0] else 'off'} (runtime switch)")
            return self._send(200, {"think": want_think(), "locked": THINK_LOCKED})
        return self._send(404, {"error": "not found"})

    def do_POST(self):
        n = int(self.headers.get("Content-Length", 0))
        try:
            req = json.loads((self.rfile.read(n) if n else b"{}").decode())
        except Exception as ex:
            return self._send(400, {"type": "error", "error": {
                "type": "invalid_request_error", "message": str(ex)}})
        if self.path.startswith("/v1/messages/count_tokens"):
            return self._send(200, {"input_tokens": len(render(req)) if E else 0})
        if not self.path.startswith("/v1/messages"):
            return self._send(404, {"error": "not found"})
        try:
            self.msg(req)
        except (ConnectionError, TimeoutError) as ex:
            # The client hung up or its socket timed out -- routine for CC
            # reconnecting.  Nobody is left to answer: latch it and log one line.
            self._gone = True
            self.close_connection = True
            logit(f"client gone before reply ({type(ex).__name__})", "warn")
        except Exception as ex:
            import traceback
            traceback.print_exc()
            # An error reply can only replace the real one if it has not
            # started: once the headers (or message_start in streaming mode) are
            # out, a second status line is protocol corruption, not an error report.
            if not getattr(self, "_hdr_sent", False):
                self._send(500, {"type": "error", "error":
                                 {"type": "api_error", "message": str(ex)}})

    def msg(self, req):
        mdl = req.get("model", "Your_Model")
        mx = int(req.get("max_tokens") or 512)
        stream = bool(req.get("stream"))
        # Whether this reply's reasoning goes to the client.  CC_THINK turns it
        # on for everyone; a request carrying an Anthropic `thinking` field asks
        # for it directly.  Defined here because the streaming setup below uses it.
        think_on = want_think(req)

        stops = list(req.get("stop_sequences") or [])
        ids, turn = prepare(req)
        mid = "msg_" + uuid.uuid4().hex[:24]
        stops += ["<|im_end|>", "<|endoftext|>", "<|im_start|>"]   # template control tokens are natural stop strings

        def run(on_token=None, on_serve=None):
            t = time.time()
            shared = False
            if BATCHER is not None:
                # The scheduler already runs requests concurrently; a lock here
                # would restore the serialisation it exists to remove.
                t0 = time.time()
                r = run_job(E, BATCHER, ids, mx, stops, turn, on_token, on_serve)
            else:
                with LK:
                    w = time.time() - t
                    if w > 1.0:
                        logit(f"waited {w:.1f}s for the engine lock "
                              f"(single context, serial)", "warn")
                    t0 = time.time()
                    pre_before, gen_before = E.st["t_pre"], E.st["t_gen"]
                    arc_before = E.st.get("arc_s", 0.0)
                    r = E.gen(ids, max_new=mx, stop=stops, turn=turn,
                              on_token=on_token, on_serve=on_serve)
            if os.environ.get("CC_DUMP"):
                with open(os.environ["CC_DUMP"], "a", encoding="utf-8") as f:
                    f.write(json.dumps({"prompt": list(ids), "gen": list(r[0]),
                                        "hit": r[2]["hit"]}) + "\n")
            info = r[2]
            # Report the split, not just the total: a request that reused 21k
            # and generated 578 can take longer than one that prefilled 25k.
            if BATCHER is not None:
                # Global counters are useless here: concurrent jobs advance
                # t_pre/t_gen too, so a delta would credit this request with
                # its neighbours' work.  A batch job carries its own split, and
                # a probe hit did no prefill, no decode and no restore.
                pf = info.get("pf") or 0.0
                gn = info.get("gn") or 0.0
                arcd = info.get("arc") or 0.0
                shared = bool(info.get("shared"))
            else:
                # No per-job figure on the serial path; the deltas were
                # taken inside the engine lock, so they are this request's.
                pf = info.get("pf")
                gn = info.get("gn")
                if pf is None:
                    pf = E.st["t_pre"] - pre_before
                if gn is None:
                    gn = E.st["t_gen"] - gen_before
                arcd = E.st.get("arc_s", 0.0) - arc_before
            sec = time.time() - t0
            # Whatever the two counters did not claim, queue time included.
            wait = max(0.0, sec - pf - gn - arcd)
            # Four speeds: forwarded tokens per forwarding second, whole
            # prompt per forwarding second (cache contribution included), the
            # decode rate over decode time alone, and output over the whole
            # request.
            pre_n = info.get("pre") or 0
            out_n = len(r[0])
            rates = []
            if pf > 0:
                if pre_n:
                    rates.append(f"{pre_n / pf:.0f}pre/s")
                if ids:
                    rates.append(f"{len(ids) / pf:.0f}ctx/s")
            if gn > 0 and out_n:
                rates.append(f"{out_n / gn:.0f}gen/s")
            if sec > 0 and out_n:
                rates.append(f"{out_n / sec:.0f}out/s")
            hit_c = "red" if info["hit"] == "batch_cold" else "green"
            # Which way thinking got turned on -- the client asking for it or
            # CC_THINK forcing it -- plus " locked" when the client asked and
            # was refused.
            think_mark = (" locked" if (req.get("thinking") and THINK_LOCKED)
                          else " req" if req.get("thinking")
                          else " env" if think_on else "")
            msg = (f"{len(ids)}+{out_n} {C(info['hit'], hit_c)} "
                   f"pre={info.get('pre')} reuse={info.get('reuse')} "
                   f"p_raw={info.get('p_raw','-')} cur={info.get('cur','-')} "
                   f"{sec:.1f}s")
            if not shared:
                # A step shared with other jobs makes the split a token-count
                # allocation, not a measurement of this request alone; record()
                # still carries the shares.
                msg += f" (prefill {pf:.1f}s + decode {gn:.1f}s"
                if wait > 0.05:
                    msg += f" + {C('wait', 'yellow')} {wait:.1f}s"
                msg += ")"
            if rates:
                msg += " " + " ".join(rates)
            if arcd > 0.001:
                msg += f" arc_restore={arcd:.2f}s"
            if turn is not None:
                msg += f" turn={turn[0]}:{turn[1].hex()[:8]}"
            if info["hit"] == "qreuse":
                msg += (f" qlevel={info.get('qpreuse')} qwhy={info.get('qwhy')} "
                        f"replayed={info.get('replayed')} "
                        f"edit={info.get('edit_applied')}ok/"
                        f"{info.get('edit_rejected')}rej")
            if info.get("seq") is not None:
                msg += f" seq={info['seq']}"
            # The busiest line in the log; its own tag so it can be picked out.
            log("req " + msg, "info", "req")
            rec = {"prompt_tokens": len(ids), "gen_tokens": len(r[0]),
                   "hit": info["hit"], "pre": info.get("pre"),
                   "reuse": info.get("reuse"), "p_raw": info.get("p_raw"),
                   "cur": info.get("cur"), "seconds": round(time.time()-t0, 3),
                   "turn_kind": None if turn is None else turn[0],
                   "turn_digest": None if turn is None else turn[1].hex(),
                   "max_tokens": mx, "stream": stream,
                   "qpreuse": info.get("qpreuse"), "qwhy": info.get("qwhy"),
                   "replayed": info.get("replayed"), "edited": info.get("edited"),
                   "edit_applied": info.get("edit_applied"),
                   "edit_rejected": info.get("edit_rejected"),
                   # Deltas, not the engine's running totals: a consumer
                   # reading this file otherwise sees a monotonically growing
                   # "seconds" that is not this request's time.
                   "prefill_seconds": round(pf, 3),
                   "generation_seconds": round(gn, 3)}
            if CAP:
                # The tokens the KV now holds past the prompt, as text.  This is
                # what the NEXT request has to re-render byte-for-byte for the
                # sequence to be reusable, and it is the only copy of it.
                rec["reply"] = r[1]
                rec["reply_ids"] = list(r[0])
            record(rec)
            return r

        def parts(text):
            think, body = split_think(text, think_on) if think_on else ("", drop_think(text))
            pre, calls = calls_of(body)
            c = []
            if think.strip():
                c.append({"type": "thinking", "thinking": think.strip(),
                          "signature": THINK_SIG})
            if pre.strip():
                c.append({"type": "text", "text": pre})
            for x in calls:
                c.append({"type": "tool_use", "id": "toolu_" + uuid.uuid4().hex[:20],
                          "name": x["name"], "input": x["arguments"]})
            return (c or [{"type": "text", "text": text}]), ("tool_use" if calls else "end_turn")

        if not stream:
            toks, text, info = run()
            c, why = parts(text)
            return self._send(200, {"id": mid, "type": "message", "role": "assistant",
                                    "model": mdl, "content": c, "stop_reason": why,
                                    "stop_sequence": None,
                                    "usage": usage(len(ids), len(toks),
                                                   info.get("reuse") or 0)})

        # ---- streaming ----
        if not self._head(200, "text/event-stream",
                          [("Cache-Control", "no-cache"),
                           ("Connection", "keep-alive")]):
            return          # already gone: nothing to stream to, and no reply to make
        # message_start is NOT sent here.  Its usage is what Claude Code writes
        # into the session transcript, and the cache fields in it can only be
        # right if the serving layer is already known -- which it is not yet:
        # the probe and the scheduler both decide later, and both decide before
        # a single token is produced.  So it goes out at the first of those
        # moments, or at the latest before any content frame.
        served = {"reuse": 0, "sent": False}
        emit0 = threading.Lock()

        def ensure_start():
            """Write message_start and the opening block once.  Caller holds emit0."""
            if served["sent"]:
                return
            served["sent"] = True
            sse(self, "message_start", {"type": "message_start", "message": {
                "id": mid, "type": "message", "role": "assistant", "model": mdl,
                "content": [], "stop_reason": None, "stop_sequence": None,
                "usage": usage(len(ids), 0, served["reuse"])}})
            # content_block_start travels with it, never up front: message_start must
            # wait until the serving layer is known, and both carry the cache
            # fields the client records.  In thinking mode the first block is
            # the reasoning, so it is opened as one.
            cb = ({"type": "thinking", "thinking": ""} if think_on
                  else {"type": "text", "text": ""})
            sse(self, "content_block_start", {"type": "content_block_start",
                "index": 0, "content_block": cb})

        def on_serve(reuse, hit):
            served["reuse"] = reuse or 0
            with emit0:
                ensure_start()

        def emit(ev, data):
            # The generation thread and this one both write to the socket -- the
            # generation thread sends text deltas while this one sends pings --
            # and interleaving two SSE frames corrupts both.
            with emit0:
                ensure_start()        # never let content precede message_start
                return sse(self, ev, data)

        def ping():
            # Deliberately NOT emit(): emit runs ensure_start, and a ping fired
            # while the serving layer is still undecided -- the engine lock held
            # by another request's long generation, or a batcher job queued
            # behind a busy home worker -- would push message_start out with
            # cache_read=0, and message_start is exactly the frame Claude Code
            # records.  A ping before message_start is legal SSE, so it goes
            # out alone; the write still takes emit0, because the generation
            # thread may be emitting deltas concurrently.
            with emit0:
                return sse(self, "ping", {"type": "ping"})

        st = Streamer(stops, think=think_on, opened=think_on) if STREAM else None
        # Which content block the deltas belong to.  A thinking block has to be
        # opened, filled and closed before the text block opens, so the two
        # cannot share index 0.
        cur_block = [0]
        block_kind = ["thinking" if think_on else "text"]

        def close_block():
            """Close the open block, signature first when it is a thinking one.

            The signature is not optional in the protocol: it is a
            signature_delta immediately before the block's stop, and a client
            that validates the shape drops a block that arrives without it.
            """
            if block_kind[0] == "thinking":
                emit("content_block_delta", {"type": "content_block_delta",
                     "index": cur_block[0],
                     "delta": {"type": "signature_delta",
                               "signature": THINK_SIG}})
            emit("content_block_stop", {"type": "content_block_stop",
                                        "index": cur_block[0]})

        def open_block(kind):
            """Move to the block for ``kind``, closing the previous one."""
            want = 0 if kind == "thinking" else (1 if think_on else 0)
            if want == cur_block[0] and block_kind[0] == kind:
                return
            close_block()
            cb = ({"type": "thinking", "thinking": ""} if kind == "thinking"
                  else {"type": "text", "text": ""})
            emit("content_block_start", {"type": "content_block_start",
                                         "index": want, "content_block": cb})
            cur_block[0], block_kind[0] = want, kind

        def on_tok(chunk):
            """What is safe to send now, computed from the raw chunks.

            The safety rules live in Streamer: nothing from a tool call, nothing
            from inside a think block unless thinking was asked for, nothing from
            a stop string, and nothing that is still a half-formed marker.  What
            comes out has to add up to exactly what the buffered path would have
            sent.
            """
            if st is None:
                return
            for kind, text in st.feed(chunk):
                open_block(kind)
                if kind == "thinking":
                    emit("content_block_delta", {"type": "content_block_delta",
                         "index": cur_block[0],
                         "delta": {"type": "thinking_delta", "thinking": text}})
                else:
                    emit("content_block_delta", {"type": "content_block_delta",
                         "index": cur_block[0],
                         "delta": {"type": "text_delta", "text": text}})

        box, done = [None, None], threading.Event()

        def work():
            # try/finally, not a bare pair: without it a raise inside run() left
            # the flag unset forever, so the handler below pinged every 6 s and
            # never reached message_stop -- and those pings keep the client's
            # idle watchdog alive, so the client waited indefinitely instead of
            # erroring.  The exception is carried out and reported below.
            try:
                box[0] = run(on_tok, on_serve)
            except BaseException as ex:       # noqa: BLE001 - reported below
                box[1] = ex
            finally:
                done.set()

        threading.Thread(target=work, daemon=True).start()
        # Event.wait returns the moment the flag is set, so a reply goes out as
        # soon as it exists.  Polling with a bare time.sleep(6.0) instead -- the
        # earlier shape -- slept the full timeout BEFORE looking, which pushed
        # every reply to the next 6 s boundary: a cache hit answered in 1 ms
        # still reached the client 6 s later.
        while not done.wait(6.0):
            ping()    # keep an idle watchdog from cutting the stream
        if box[1] is not None:
            # The response headers are already sent, so the only honest report is
            # an SSE error event, then close.
            emit("error", {"type": "error",
                           "error": {"type": "api_error", "message": str(box[1])}})
            self.close_connection = True
            return
        if box[0] is None:
            # Unreachable while the loop above waits on done: work() sets
            # box[0] or box[1] in every path.  Asserted so that anything which
            # leaves that loop early fails here with a reason, instead of dying
            # on the unpack with "cannot unpack non-sequence NoneType".
            raise RuntimeError("generation finished without a result")
        toks, text, info = box[0]
        # Everything below writes frames directly, so make sure message_start has
        # gone out first.  It normally has by now (on_serve fired at admission,
        # or the first delta went through emit), but a reply that produced no
        # streamed text at all would otherwise reach message_delta without it.
        with emit0:
            ensure_start()

        # Everything is sent after generation completes, not while generating --
        # tool blocks cannot be streamed character by character or CC sees half a
        # text block first.
        think, body = split_think(text, think_on) if think_on else ("", drop_think(text))
        pre, calls = calls_of(body)

        def send_text(t):
            if not t:
                return
            open_block("text")
            emit("content_block_delta", {"type": "content_block_delta",
                 "index": cur_block[0],
                 "delta": {"type": "text_delta", "text": t}})

        if st is not None:
            # Whatever the safety rules held back, now that the real text is
            # known.  After this the client holds exactly `pre`.
            send_text(st.finish(pre))
            if st.mismatch:
                logit("what was streamed is not a prefix of the buffered text; "
                      "no correction sent, see stream.py", "warn")
        else:
            # No streamer at all (CC_STREAM=0), so nothing has gone out yet: the
            # reasoning and the answer both have to be sent from here.
            if think.strip():
                open_block("thinking")
                emit("content_block_delta", {"type": "content_block_delta",
                     "index": cur_block[0],
                     "delta": {"type": "thinking_delta", "thinking": think.strip()}})
            send_text(pre)
        close_block()
        base = cur_block[0] + 1
        for i, c in enumerate(calls, start=base):
            sse(self, "content_block_start", {"type": "content_block_start", "index": i,
                "content_block": {"type": "tool_use",
                                  "id": "toolu_" + uuid.uuid4().hex[:20],
                                  "name": c["name"], "input": {}}})
            sse(self, "content_block_delta", {"type": "content_block_delta", "index": i,
                "delta": {"type": "input_json_delta",
                          "partial_json": json.dumps(c["arguments"], ensure_ascii=False)}})
            sse(self, "content_block_stop", {"type": "content_block_stop", "index": i})
        sse(self, "message_delta", {"type": "message_delta",
            "delta": {"stop_reason": "tool_use" if calls else "end_turn",
                      "stop_sequence": None},
            # Repeats the whole usage rather than just output_tokens.  Claude
            # Code is known to record the fields from message_start; this one
            # carries the same numbers so a reader that prefers the last usage
            # in the stream sees them too.
            "usage": usage(len(ids), len(toks), info.get("reuse") or 0)})
        sse(self, "message_stop", {"type": "message_stop"})
        # An SSE response has neither Content-Length nor chunked encoding, so
        # under HTTP/1.1 the client can only tell the response ended by the
        # connection CLOSING.  message_stop is only the SSE layer.  Without this,
        # keep-alive reuses the connection and the next request falls into a
        # black hole.
        self.close_connection = True


class Srv(ThreadingHTTPServer):
    daemon_threads = True
    allow_reuse_address = True

    def handle_error(self, req, addr):
        """CC reconnecting or resetting after a timeout is normal; do not pollute
        the log with a traceback for it."""
        if isinstance(sys.exc_info()[1], (ConnectionResetError, ConnectionAbortedError,
                                          BrokenPipeError, TimeoutError, OSError)):
            return
        super().handle_error(req, addr)

    def process_request_thread(self, req, addr):
        try:
            super().process_request_thread(req, addr)
        except (ConnectionResetError, ConnectionAbortedError, BrokenPipeError,
                TimeoutError, OSError):
            pass


def main():
    global E
    ap = argparse.ArgumentParser()
    ap.add_argument("--port", type=int, default=8788)
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--n-ctx", type=int, default=131072)
    a = ap.parse_args()
    global BATCHER
    workers = 1
    if os.environ.get("CC_BATCH") == "1":
        workers = max(2, int(os.environ.get("CC_BATCH_N", "4")))
    # The whole sequence budget -- workers, DDC's verification scratch, archive
    # slots -- comes from eng.plan_sequences, which owns the layout and is the
    # same function Eng reads its indices off.  Sized in one place on purpose:
    # when srv.py sized the archive and Eng sized DDC's doubling separately, the
    # two agreed only by accident, and DDC's scratch landed on a sequence the
    # archive had already claimed.
    nseq, n_ctx, ddc_seq = plan_sequences(a.n_ctx, workers)
    if nseq > 1:
        # n_ctx is the POOL: the cells are n_ctx in total and llama.cpp divides
        # them across the sequences, which is what makes this cost memory rather
        # than nothing.  How it is derived -- flat multiplication, or workers at
        # full window plus archive slots at CC_ARCHIVE_CAP -- is pool_for's
        # business, and pool_terms renders that same function for this line
        # rather than paraphrasing it, so the log cannot describe a layout the
        # arithmetic did not produce.
        scratch_n = ddc_scratch_count(workers)
        logit(f"nseq {nseq} = {workers} worker(s) + "
              f"{f'{scratch_n} DDC scratch + ' if scratch_n else ''}"
              f"{arc_slot_count()} archive slot(s), "
              f"n_ctx {a.n_ctx} -> {n_ctx} (pool: {pool_terms(a.n_ctx, workers)})")
    log_setup(LOGDIR)
    log_setup(LOGDIR)
    logit(f"loading engine n_ctx={n_ctx} nseq={nseq}")
    E = Eng(n_ctx=n_ctx, nseq=nseq, workers=workers, log=logit)
    # Say the coupling out loud rather than leaving it to be discovered as a
    # cache that quietly stopped working.  The template renders a finished
    # assistant turn from its content, so it can only reproduce the KV if the
    # reasoning came back -- and reasoning comes back only if the client was
    # given it.  With thinking locked off there is no reasoning to give back.
    if E.ct_mode == 2 and THINK_LOCKED:
        logit("WARNING: CC_TMPL=2 with CC_THINK=0 -- the template cannot "
              "re-render the closed empty reasoning block it generated from, so "
              "every turn after an answer re-prefills its whole prompt. "
              "Use CC_THINK=1 (keeps the cache, and the model's reasoning), or "
              "CC_TMPL=1 (keeps the closed block AND the cache, no reasoning).")
    if E.ct_mode == 1 and not THINK_LOCKED:
        logit("note: CC_TMPL=1 renders the assistant turns itself, so reasoning "
              "still round-trips; CC_TMPL=2 hands them to the template.")
    if workers > 1:
        BATCHER = Batcher(E, log=logit)
        logit(f"scheduler up: {len(E.work_seqs)} worker sequences "
              f"{E.work_seqs}, requests run concurrently")
    try:
        os.makedirs(LOGDIR, exist_ok=True)
    except OSError as ex:
        # logit()/record() swallow the same failure, so aborting here after the
        # 5.5 GB model is loaded would contradict the module's own rule.
        logit(f"cannot create log dir {LOGDIR}: {ex} (continuing without it)")
    s = Srv((a.host, a.port), Api)
    logit(f"listening on http://{a.host}:{a.port}")
    logit(f"point Claude Code at: ANTHROPIC_BASE_URL=http://{a.host}:{a.port}")
    logit(f"logs -> {LOGDIR}")
    logit("single context, serial -- concurrent requests queue, that is the inherent bottleneck")
    try:
        s.serve_forever()
    except KeyboardInterrupt:
        logit("exit")
