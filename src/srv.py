"""HTTP layer: Anthropic Messages API compatibility for Claude Code.

Three adapters keep the KV prefix aligned; a drifting prefix costs a full
prefill on every turn.
  A. counter normalization: CC injects <total_tokens>N tokens left</total_tokens>
     and N changes every request, so it is pinned to a constant.
  B. assistant header: the header used when generating and the one used when
     re-rendering history must be byte-identical.
  C. empty block filter: CC's empty text blocks would add newlines on join.
A and B each have a kill switch for A/B comparisons.
"""
